# TODO  Напишите функцию count_letters
def count_letters(text):
    # Создаем пустой словарь для подсчета букв
    letter_counts = {}
    # Проходим по всем символам в тексте
    for char in text:
        # Проверяем, является ли символ буквой
        if char.isalpha():
            # Приводим букву к нижнему регистру
            lower_char = char.lower()
            # Увеличиваем счетчик для этой буквы
            # Метод get возвращает текущее значение или 0, если ключа нет
            letter_counts[lower_char] = letter_counts.get(lower_char, 0) + 1
    return letter_counts
# TODO Напишите функцию calculate_frequency
def calculate_frequency(letter_counts):
    # Вычисляем общее количество букв в тексте
    total_letters = sum(letter_counts.values())
    # Создаем словарь для частот
    frequencies = {}
    # Для каждой буквы вычисляем частоту
    for letter, count in letter_counts.items():
        frequency = count / total_letters
        frequencies[letter] = frequency

    return frequencies

